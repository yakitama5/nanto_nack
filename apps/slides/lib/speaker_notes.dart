/// 発表の原稿（スピーカーノート）。
///
/// プレゼンター表示の下段に出る文字列を、**このファイルにだけ**置いている。
/// 原稿はレイアウトと関係なく何度も推敲するものなので、スライドの実装から
/// 切り離して、ここだけ見て直せるようにしてある。
///
/// 各定数は `lib/slides/*.dart` の `FlutterDeckSlideConfiguration.speakerNotes`
/// から参照する。**`const` のまま保つこと**（スライドの構成は const で組まれている
/// ため、文字列連結や補間を入れると呼び出し側がコンパイルできなくなる）。
///
/// ## 書くときの制約
///
/// - **装飾は効かない。** ただの `Text` で描かれるので、Markdown の `**強調**` は
///   そのまま記号として出る。使えるのは改行と全角記号（`［］` など）だけ
/// - **ステップ単位では切り替わらない。** `speakerNotes` は1スライドに1つ。
///   ステップのある [whySlide] は本文にステップ番号を書いて対応を取っている
/// - **尺は全体で3分。** 各定数の先頭に想定の時間帯を書いてある。
///   日本語の発話はおよそ 300〜350 字/分なので、30秒の枠なら 150〜175 字が目安
abstract final class SpeakerNotes {
  /// 1枚目「つかみ」 0:00-0:30
