  /// 6枚目「クロージング」 2:45-3:00
  static const closingSlide = '''
［2:45-3:00／言い切って終わる］

読めなくても伝わるUIが、いいUI。

NantoNack、App Store と Google Play で公開中です。
QRからどうぞ。

ありがとうございました。''';
}
