［0:00-0:30］

［まず何も言わずに5秒待つ。会場に画面を読ませる時間］

この画面、操作できますか？

お題はひとつだけです。水を2つ、カートに入れる。
ただし、文字はひとつも読めません。全部、架空の言語です。

……どこを押しますか？

［ここでもう3秒待ってから次のスライドへ］''';

  /// 2枚目「手がかり」 0:30-1:05
  ///
  /// このスライドだけ6ステップある。`speakerNotes` はステップごとに
  /// 切り替わらないので、本文の側にステップ番号を書いて対応を取っている。
  /// **番号を消すと発表中に現在地が分からなくなる。**
  static const whySlide = '''
［0:30-1:05／6ステップ。矢印キーで1つずつ送る］

読めないのに、たぶん分かりましたよね。何を見たんでしょうか。

［ステップ1：まだ何も出さない。2秒待って会場に考えさせる］

［ステップ2 ①形］カートの形。買い物かごの形だと、形だけで分かる。
［ステップ3 ②記号］円マーク。数字が読めなくても値段だと分かる。
［ステップ4 ③色］黄色い丸ボタン。押せそうな色をしている。
［ステップ5 ④位置］画面下の帯。下にあれば切り替えだと分かる。

［ステップ6 種明かし］どれも、文字じゃないんです。
今回のアプリはこのように、文字が読めなくても「わかる」という体験を味わうゲームです。
''';

  /// 3枚目「なぜ作ったか」 1:05-1:35
  static const backgroundSlide = '''
［1:05-1:35］

ゲーム作成で重点を置いたのは「あたらしいジャンルを作る」という点です。
パズルでもあり、クイズでもある、新しいアハ体験のようなゲームを目指しました。

難しかったのは、そのためにゲーム性をある程度犠牲にした点です。

このゲームでは駆け引きやリスク・リターンといったものは扱いづらいと思ったので、
代わりに取ったのが、「あるある」と「アハ体験」です。
うまくなるアプリではなく、わかるアプリに舵を切ることにしました。
''';

  /// 4枚目「コンセプト」 1:35-2:10
  static const wonderSlide = '''
［1:35-2:10／本編の山場。ここだけゆっくり話す］

形・色・位置。
いま皆さんが使った手がかりは、普段はまったく意識していないものです。

読めない画面に放り込まれて、はじめて気づく。

「わかった！」と思うこの瞬間そのものが、このアプリが届けたいものです。
機能ではなく、感覚の再発見です。
''';

  /// 5枚目「言語化」 2:10-2:45
  static const insightSlide = '''
［2:10-2:45］

ただ、「わかった」で終わると、たいてい忘れます。

クリアすると、いま使った手がかりの解説が出ます。
右にあるのは実際のアプリの画面そのものです。

アイコン、色、パターン。さっきの答え合わせが、そのまま出る。

触ってわかる。その場で言語化する。だから、残る。
プレイした方に思い出や知識を残す意味で解説を付け加えています。
